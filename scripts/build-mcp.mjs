// Build the MCP server (docs/mcp.md):
//   1. public/mcp/rules-compact.json  — a slim copy of public/rules.json for the server: same slugs, names,
//      parentSlug, page reference and verbatim plain text (bodyIndex); rich text only as tables (weapon
//      profiles, charts, spell blocks), plus errata/FAQ and the lore spell lists. ~2 MB instead of 16 MB,
//      so a cold function loads in a fraction of the time. public/rules.json itself is only READ.
//   2. api/mcp.js — mcp/entry.ts (mcp/server.ts) and the src/lib modules it uses, bundled into one ESM file with
//      rolldown (comes with Vite). Vercel deploys it as the /api/mcp function as-is.
//
//   node scripts/build-mcp.mjs          write both
//   node scripts/build-mcp.mjs --check  exit 1 if either file is out of date (used by npm run test:mcp)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const RULES_OUT = join(root, 'public/mcp/rules-compact.json');
const BUNDLE_OUT = join(root, 'api/mcp.js');

// ── 1. compact rules ──────────────────────────────────────────────────────────────────────────────

function tablesOf(body) {
  const out = [];
  const text = (n) => (!n || typeof n !== 'object' ? '' : n.nodeType === 'text' ? n.value ?? '' : (n.content ?? []).map(text).join(''));
  const walk = (n) => {
    if (!n || typeof n !== 'object') return;
    if (n.nodeType === 'table') {
      out.push((n.content ?? []).filter((r) => r.nodeType === 'table-row').map((r) => (r.content ?? []).map((c) => text(c).trim())));
      return;
    }
    (n.content ?? []).forEach(walk);
  };
  walk(body);
  return out;
}

export function compactRules(data) {
  const R = data.rules;
  const sections = new Set((data.nav ?? []).map((x) => x.slug));
  const spellSlugs = new Set(Object.values(data.lores ?? {}).flatMap((l) => (l.spells ?? []).map((s) => s.slug)));
  // tow.whfb.app page path, from how scripts/scrape.mjs fetched the page.
  const pathOf = (r) => {
    if (r.parentSlug) return `${r.parentSlug}/${r.slug}`;
    if (sections.has(r.slug)) return r.slug;
    if (spellSlugs.has(r.slug) && r.slug.startsWith('spell-')) return `spell/${r.slug.slice(6)}`;
    return null;
  };
  const rules = {};
  for (const slug of Object.keys(R).sort()) {
    const r = R[slug];
    const tables = tablesOf(r.body);
    let url = pathOf(r);
    // A weapon "(Profile)" table is shown on the weapon's own page.
    if (!url && /-profile$/.test(slug)) {
      const base = R[slug.replace(/(-ranged|-combat)?-profile$/, '')];
      if (base) url = pathOf(base);
    }
    rules[slug] = {
      slug,
      name: r.name,
      parentSlug: r.parentSlug ?? null,
      pageReference: r.pageReference ?? null,
      ...(r.ruleType ? { ruleType: r.ruleType } : {}),
      ...(Array.isArray(r.association) && r.association.length ? { association: r.association } : {}),
      bodyIndex: r.bodyIndex ?? '',
      ...(tables.length ? { tables } : {}),
      ...(Array.isArray(r.childSlugs) && r.childSlugs.length ? { childSlugs: r.childSlugs } : {}),
      url,
    };
  }
  const note = (n) => ({ slug: n.slug, name: n.name, bodyIndex: n.bodyIndex ?? '', ...(n.source ? { source: n.source } : {}), ...(n.refSlugs?.length ? { refSlugs: n.refSlugs } : {}) });
  const lores = {};
  for (const [k, l] of Object.entries(data.lores ?? {})) lores[k] = { slug: l.slug, name: l.name, spells: (l.spells ?? []).map((s) => ({ slug: s.slug, name: s.name, ...(s.signature ? { signature: true } : {}) })) };
  return {
    _generated: 'by scripts/build-mcp.mjs from public/rules.json — do not edit',
    source: data.source,
    scrapedAt: data.scrapedAt,
    rules,
    errata: (data.errata ?? []).map(note),
    faq: (data.faq ?? []).map(note),
    lores,
  };
}

// ── 2. bundle ─────────────────────────────────────────────────────────────────────────────────────

const BANNER = `// GENERATED by scripts/build-mcp.mjs from mcp/*.ts and src/lib — do not edit; run \`npm run build:mcp\`.
// Old World Companion MCP server (Vercel Node function at /api/mcp). See docs/mcp.md.`;

async function bundle() {
  const b = await rolldown({
    input: join(root, 'mcp/entry.ts'),
    platform: 'node',
    logLevel: 'silent',
    resolve: { extensions: ['.ts', '.js', '.json'] },
  });
  const { output } = await b.generate({ format: 'esm', banner: BANNER });
  await b.close();
  const chunks = output.filter((o) => o.type === 'chunk');
  if (chunks.length !== 1) throw new Error(`expected one chunk, got ${chunks.length}`);
  return chunks[0].code;
}

// ── run ───────────────────────────────────────────────────────────────────────────────────────────

const rulesJson = `${JSON.stringify(compactRules(JSON.parse(readFileSync(join(root, 'public/rules.json'), 'utf8'))))}\n`;
const code = await bundle();
const same = (file, content) => existsSync(file) && readFileSync(file, 'utf8') === content;

if (check) {
  const stale = [[RULES_OUT, rulesJson], [BUNDLE_OUT, code]].filter(([f, c]) => !same(f, c)).map(([f]) => f);
  if (stale.length) {
    console.error(`Out of date (run npm run build:mcp): ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log('MCP build is up to date.');
} else {
  mkdirSync(dirname(RULES_OUT), { recursive: true });
  mkdirSync(dirname(BUNDLE_OUT), { recursive: true });
  writeFileSync(RULES_OUT, rulesJson);
  writeFileSync(BUNDLE_OUT, code);
  console.log(`Wrote ${RULES_OUT} (${(rulesJson.length / 1e6).toFixed(2)} MB) and ${BUNDLE_OUT} (${(code.length / 1e3).toFixed(0)} kB).`);
}
